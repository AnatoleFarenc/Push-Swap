#include "libft.h"

t_list	*ft_lstnew(void *content)
{
	t_list	*new_elem;

	new_elem = malloc(sizeof(t_list));
	if (!new_elem)
		return (NULL);
	if (content)
		new_elem->content = content;
	new_elem->next = NULL;
	return (new_elem);
}
